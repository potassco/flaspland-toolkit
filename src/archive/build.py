"""Build dummy Flatland environments and emit .pkl, .lp, and .png files.

This is a placeholder implementation: it prints pre-decided information
and writes small, valid placeholder files so the CLI pipeline can be
exercised end-to-end before the real Flatland + ASP logic is wired in.
"""

from __future__ import annotations

import pickle
from pathlib import Path
from typing import Any


# A minimal 1x1 transparent PNG (67 bytes). Lets file explorers open the
# generated .png without needing Pillow at this stage.
_PLACEHOLDER_PNG = bytes.fromhex(
    "89504e470d0a1a0a0000000d49484452000000010000000108060000001f15c4"
    "890000000d49444154789c6300010000000500010d0a2db40000000049454e44"
    "ae426082"
)


def build_environment(
    params: dict[str, Any],
    output_stem: Path,
    overwrite: bool = False,
) -> dict[str, Path]:
    """Create one placeholder environment and write its .pkl/.lp/.png.

    Returns a dict mapping {"pkl", "lp", "png"} -> Path.
    """
    pkl_path = output_stem.with_suffix(".pkl")
    lp_path = output_stem.with_suffix(".lp")
    png_path = output_stem.with_suffix(".png")

    if not overwrite and pkl_path.exists():
        raise FileExistsError(
            f"{pkl_path} already exists. Use --overwrite to regenerate."
        )

    output_stem.parent.mkdir(parents=True, exist_ok=True)

    print(f"  [dummy build] width={params.get('width')} "
          f"height={params.get('height')} "
          f"agents={params.get('agents')} "
          f"seed={params.get('seed')}")

    # .pkl: pickle the params dict itself as a stand-in for RailEnv.
    with open(pkl_path, "wb") as f:
        pickle.dump({"placeholder": True, "params": params}, f)

    # .lp: a few hardcoded ASP facts.
    lp_path.write_text(
        "% placeholder facts generated by `flasp build`\n"
        f"% seed={params.get('seed')}, agents={params.get('agents')}\n"
        "train(0).\n"
        "train(1).\n"
        "cell((0,0), 0).\n"
        "cell((0,1), 1025).\n"
        "start(0, (0,0), 0, e).\n"
        "end(0, (10,10), 50).\n",
        encoding="utf-8",
    )

    # .png: a 1x1 transparent placeholder.
    png_path.write_bytes(_PLACEHOLDER_PNG)

    return {"pkl": pkl_path, "lp": lp_path, "png": png_path}
